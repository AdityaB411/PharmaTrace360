def esc(s: str) -> str:
    """Escape a string for MySQL single-quoted literal."""
    if s is None:
        return "NULL"
    return s.replace("\\", "\\\\").replace("'", "\\'")


def q(s: str | None) -> str:
    """Return 'escaped-value' or NULL."""
    if s is None or s.strip() == "":
        return "NULL"
    return f"'{esc(s)}'"


def subq_role(role_name: str) -> str:
    return f"(SELECT role_id FROM Roles WHERE role_name = '{esc(role_name)}')"


def subq_mfr(company_name: str) -> str:
    return f"(SELECT manufacturer_id FROM Manufacturers WHERE company_name = '{esc(company_name)}')"


def subq_supplier(supplier_name: str) -> str:
    return f"(SELECT supplier_id FROM Suppliers WHERE supplier_name = '{esc(supplier_name)}')"


def subq_ingredient(ingredient_name: str) -> str:
    return f"(SELECT ingredient_id FROM Ingredients WHERE ingredient_name = '{esc(ingredient_name)}')"


def subq_medicine(brand_name: str, manufacturer: str) -> str:
    return (
        f"(SELECT medicine_id FROM Medicines "
        f"WHERE brand_name = '{esc(brand_name)}' "
        f"AND manufacturer_id = {subq_mfr(manufacturer)})"
    )


def subq_factory(factory_name: str) -> str:
    return f"(SELECT factory_id FROM Factories WHERE factory_name = '{esc(factory_name)}')"


def subq_batch(batch_number: str) -> str:
    return f"(SELECT batch_id FROM Production_Batches WHERE batch_number = '{esc(batch_number)}')"


def subq_user(email: str) -> str:
    return f"(SELECT user_id FROM Users WHERE email = '{esc(email)}')"


def subq_qr(code: str) -> str:
    return f"(SELECT qr_id FROM QR_Codes WHERE code = '{esc(code)}')"


def subq_delivery(supplier: str, ingredient: str, manufacturer: str, cert: str) -> str:
    return (
        f"(SELECT delivery_id FROM Material_Deliveries "
        f"WHERE supplier_id = {subq_supplier(supplier)} "
        f"AND ingredient_id = {subq_ingredient(ingredient)} "
        f"AND manufacturer_id = {subq_mfr(manufacturer)} "
        f"AND certificate_number = '{esc(cert)}')"
    )


# Deterministic QR code generator: PT360- + 12 hex from uuid5
_QR_NAMESPACE = uuid.UUID("6ba7b810-9dad-11d1-80b4-00c04fd430c8")  # URL namespace


def make_qr_code(batch_number: str, pack_index: int) -> str:
    """Generate a deterministic QR code string."""
    name = f"{batch_number}:pack:{pack_index}"
    u = uuid.uuid5(_QR_NAMESPACE, name)
    return "PT360-" + u.hex[:12].upper()


# ---------------------------------------------------------------------------
# Read CSV
# ---------------------------------------------------------------------------
def read_csv():
    rows = []
    with open(CSV_PATH, newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        for r in reader:
            # strip whitespace from keys and values
            row = {k.strip(): (v.strip() if v else "") for k, v in r.items()}
            if row.get("medicine_name", "").strip():
                rows.append(row)
    return rows


